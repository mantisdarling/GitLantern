import { CommandHistoryItem } from "@/lib/types";

export function generateCheatsheetMarkdown(
  historyItems: CommandHistoryItem[],
  customTitle: string = "Git Lantern - My Personal Git Cheat Sheet"
): string {
  const dateStr = new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  let content = `# ${customTitle}\n`;
  content += `*Generated by Git Lantern on ${dateStr}*\n\n`;
  content += `> "A developer who masters Git commands never fears a merge conflict."\n\n`;
  content += `## Executed and Synthesized Commands\n\n`;

  if (historyItems.length === 0) {
    content += `*No commands recorded in this session yet. Try synthesizing a scenario or typing in the terminal simulator!*\n\n`;
  } else {
    historyItems.forEach((item, index) => {
      content += `### ${index + 1}. \`${item.command}\`\n`;
      content += `- **Explanation:** ${item.explanation || "Direct terminal command execution"}\n`;
      content += `- **Source:** ${item.source}\n`;
      content += `- **Timestamp:** ${item.timestamp}\n\n`;
    });
  }

  content += `## Essential Quick Reference\n\n`;
  content += `| Task | Command |\n`;
  content += `| :--- | :--- |\n`;
  content += `| Stage all files | \`git add .\` |\n`;
  content += `| Check status | \`git status\` |\n`;
  content += `| Create & switch branch | \`git checkout -b <branchName>\` |\n`;
  content += `| Commit staged changes | \`git commit -m "feat: description"\` |\n`;
  content += `| Push with upstream tracking | \`git push -u origin <branchName>\` |\n`;
  content += `| Undo last commit safely | \`git reset --soft HEAD~1\` |\n`;
  content += `| Stash working files | \`git stash save "wip"\` |\n`;
  content += `| Discard modified file | \`git restore <file>\` |\n`;
  content += `| Safe force push | \`git push --force-with-lease\` |\n\n`;
  content += `\n*Git Lantern Developer Tool | https://github.com/mantisdarling/GitLantern*\n`;

  return content;
}

export function downloadCheatsheet(historyItems: CommandHistoryItem[]): void {
  const markdownText = generateCheatsheetMarkdown(historyItems);
  const blob = new Blob([markdownText], { type: "text/markdown;charset=utf-8;" });
  const downloadUrl = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = downloadUrl;
  anchor.download = "git-lantern-cheatsheet.md";
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(downloadUrl);
}
